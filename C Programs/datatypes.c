#include<stdio.h>

int main()
{
    int iNo1=10;  // size=4 byte

    float fValue=3.14; // 4 byte

    double dData=6.28; // 8 byte

    char cValue='M'; // 1 byte

    printf("Integer is %d \n",iNo1);

    printf("Float is %f \n",fValue);

    printf("Double is %f \n",dData);

    printf("Character is %c \n",cValue);

    return 0;
}